"""Channel-owned capabilities. No SDK client, worker, adapter or credentials."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Protocol


class ParticipationPort(Protocol):
    platform: str
    home: Path
    owner_id: str
    groups: frozenset[str]
    contact_contract: int
    public_context_contract: int

    def ready(self) -> bool: ...
    def epoch(self) -> int: ...
    def recalled(self, chat: str, message_id: str) -> bool: ...
    def set_registration_key(self, key: tuple[str, str]) -> None: ...
    def detach(self) -> None: ...
    def issue_optional(self, event: Any) -> Any: ...
    def observe_activity(self, event: Any) -> None: ...
    def invalidate_optional(self, chat: str | None = None, *, keep_pure_image: bool = False) -> None: ...
    def dispatch_optional(self, event: Any) -> Any: ...
    async def wait_visual_context(self, chat: str, *, max_seconds: float) -> None: ...
    async def prepare_idle(self, chat: str, task_id: str, context: list[dict]) -> Any: ...
    def claim_idle(self, chat: str, task_id: str) -> Any: ...
    async def send_idle(self, grant: Any, text: str, consume: Callable, valid: Callable) -> bool: ...
    def last_receipt(self, chat: str) -> str | None: ...
    def next_opportunity(self, chat: str, *, excluded: frozenset[str]) -> Any: ...
    async def send_opportunity(self, grant: Any, offer: Any, consume: Callable, valid: Callable) -> bool: ...
    def report_contact_feedback(self, chat: str, recipient: str, reference: str, status: str) -> None: ...
